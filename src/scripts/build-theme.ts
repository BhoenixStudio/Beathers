import fs from 'fs-extra'; // Reverted to namespace import
import * as path from 'node:path';
import { execSync } from 'node:child_process';
import { parse, Node as ScssAstNode } from 'scss-parser';
import { fileURLToPath } from 'node:url';

// ES Module equivalent for __dirname
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const projectRoot = path.resolve(__dirname, '../..');
const generatedVariablesPath = path.join(projectRoot, 'src', 'scss', '_variables.scss');
const defaultsScssPath = path.join(projectRoot, 'src', 'scss', 'settings', '_defaults.scss');
const buildScriptPath = path.join(projectRoot, 'build.ts');
const userConfigFiles = ['beathers.config.js', 'beathers.config.ts', 'beathers.config.json'];

interface ColorVariant {
  light: string;
  dark: string;
}

interface ColorMap {
  [colorName: string]: ColorVariant | string;
}

interface FontVariantDetail {
  title: string;
  isLocal?: boolean;
}

interface FontVariants {
  [lang: string]: FontVariantDetail;
}

interface FontFamily {
  variants: FontVariants;
}

interface FontMap {
  [fontKey: string]: FontFamily;
}

interface ScssNodeValue {
  type: string;
  value: string | number | ScssNodeValue[];
  start?: { line: number; column: number };
  end?: { line: number; column: number };
}

interface ThemeBase {
  colors: ColorMap;
  fontMainPath: string;
  fontFormat: string;
  fontWeights: string[];
  fontStyles: string[];
  textTruncate: number;
  fonts: FontMap;
}

interface Theme extends ThemeBase {
  [key: string]: ThemeValue | ColorMap | FontMap | string[] | undefined;
}

function isObject(item: unknown): item is Record<string, unknown> {
  return item !== null && typeof item === 'object' && !Array.isArray(item);
}

type DeepPartial<T> = {
  [P in keyof T]?: T[P] extends object ? DeepPartial<T[P]> : T[P];
};

function mergeThemes<T extends Record<string, unknown>>(base: T, updates: DeepPartial<T>): T {
  const output = { ...base };

  for (const key in updates) {
    if (Object.hasOwn(updates, key)) {
      const typedKey = key as keyof T;
      const baseValue = output[typedKey];
      const updateValue = updates[typedKey];

      if (isObject(baseValue) && isObject(updateValue)) {
        output[typedKey] = mergeThemes(
          baseValue as Record<string, unknown>,
          updateValue as DeepPartial<Record<string, unknown>>
        ) as T[keyof T];
      } else if (updateValue !== undefined) {
        output[typedKey] = updateValue as T[keyof T];
      }
    }
  }
  return output;
}

type ThemeValue =
  | string
  | number
  | string[]
  | boolean
  | Record<string, string | number | boolean>
  | Array<string | number | boolean>;

async function loadUserConfig(): Promise<DeepPartial<Theme> | null> {
  for (const configFile of userConfigFiles) {
    const configPath = path.join(projectRoot, configFile);
    try {
      await fs.access(configPath);
      if (configFile.endsWith('.json')) {
        const fileContent = await fs.readFile(configPath, 'utf8');
        return JSON.parse(fileContent) as DeepPartial<Theme>;
      } else if (configFile.endsWith('.js') || configFile.endsWith('.ts')) {
        const absoluteConfigPath = path.resolve(configPath);
        const modulePath = `file://${absoluteConfigPath.replace(/\\/g, '/')}`;
        const configModule = await import(modulePath);
        return (configModule.default ?? configModule) as DeepPartial<Theme>;
      }
    } catch {
      // Configuration file not found or not accessible, try the next one
      continue;
    }
  }
  return null;
}

function formatScssValue(value: ThemeValue | undefined, themeColors: ColorMap): string {
  if (value === undefined) return 'null';
  if (typeof value === 'string') {
    if (
      /^(#|rgb|hsl|transparent|currentColor|inherit)/.test(value) ||
      Object.hasOwn(themeColors, value)
    ) {
      return value;
    }
    return `'${value.replace(/'/g, "\\'")}'`; // Corrected escaping for single quotes within SCSS strings
  }
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);

  if (Array.isArray(value))
    return `(${value.map(v => formatScssValue(v, themeColors)).join(', ')})`;

  if (isObject(value)) {
    let mapString = '(';
    const entries = Object.entries(value);
    for (let i = 0; i < entries.length; i++) {
      const [k, v] = entries[i];
      mapString += `'${k}': ${formatScssValue(v as ThemeValue, themeColors)}`;
      if (i < entries.length - 1) mapString += ', ';
    }
    mapString += ')';
    return mapString;
  }
  return String(value);
}

function convertThemeToScss(theme: Theme): string {
  let scssString = '// Generated by build-theme.ts\n';
  scssString += '// Do not edit this file directly.\n\n';

  const toScss = (value: ThemeValue | undefined) => formatScssValue(value, theme.colors);

  scssString += '// --- Colors ---\n';
  for (const [name, colorValue] of Object.entries(theme.colors)) {
    if (typeof colorValue === 'string') {
      scssString += `$color-${name}: ${toScss(colorValue)} !default;\n`;
    } else if (
      isObject(colorValue) &&
      typeof colorValue.light === 'string' &&
      typeof colorValue.dark === 'string'
    ) {
      scssString += `$color-${name}-light: ${toScss(colorValue.light)} !default;\n`;
      scssString += `$color-${name}-dark: ${toScss(colorValue.dark)} !default;\n`;
    }
  }
  scssString += '\n';

  scssString += '// --- Typography ---\n';
  scssString += `$font-main-path: ${toScss(theme.fontMainPath)} !default;\n`;
  scssString += `$font-format: ${toScss(theme.fontFormat)} !default;\n`;
  scssString += `$font-weights: ${toScss(theme.fontWeights)} !default;\n`;
  scssString += `$font-styles: ${toScss(theme.fontStyles)} !default;\n`;
  scssString += `$text-truncate: ${toScss(theme.textTruncate)} !default;\n`;
  scssString += '\n';

  scssString += '// --- Font Stacks ---\n';
  scssString += '$fonts: (\n';
  const fontEntries = Object.entries(theme.fonts);
  for (let i = 0; i < fontEntries.length; i++) {
    const [fontKey, fontData] = fontEntries[i];
    scssString += `  '${fontKey}': (\n`;
    scssString += `    variants: (\n`;
    const variantEntries = Object.entries(fontData.variants);
    for (let j = 0; j < variantEntries.length; j++) {
      const [lang, details] = variantEntries[j];
      // Corrected string literal for isLocalStr
      const isLocalStr = details.isLocal ? ', isLocal: true' : '';
      scssString += `      '${lang}': (title: ${toScss(details.title)}${isLocalStr}),\n`;
    }
    scssString += '    )\n';
    // Corrected string literal for comma separation
    scssString += `  )${i < fontEntries.length - 1 ? ',' : ''}\n`;
  }
  scssString += ') !default;\n';

  scssString += '\n// --- Other Settings ---\n';
  for (const [key, value] of Object.entries(theme)) {
    if (
      ![
        'colors',
        'fontMainPath',
        'fontFormat',
        'fontWeights',
        'fontStyles',
        'textTruncate',
        'fonts',
      ].includes(key)
    ) {
      if (value !== undefined) {
        scssString += `$${key.replace(/([A-Z])/g, '-$1').toLowerCase()}: ${toScss(value as ThemeValue)} !default;\n`;
      }
    }
  }

  return scssString;
}

function parseValueNode(
  node: ScssNodeValue | ScssAstNode
): string | number | Record<string, unknown> | Array<unknown> {
  if (typeof node.value === 'string' || typeof node.value === 'number') {
    if (node.type === 'string_single' || node.type === 'string_double') {
      return String(node.value).replace(/['"]/g, '');
    }
    if (node.type === 'color_hex') {
      return `#${node.value}`;
    }
    return node.value;
  }

  if (Array.isArray(node.value)) {
    if (node.type === 'arguments' || node.type === 'parentheses') {
      const values = node.value.filter(
        (n: ScssNodeValue | ScssAstNode) =>
          n.type !== 'space' && n.type !== 'operator' && String(n.value).trim() !== ','
      );
      if (values.some((n: ScssNodeValue | ScssAstNode) => n.type === 'declaration')) {
        const map: Record<string, unknown> = {};
        values.forEach((item: ScssNodeValue | ScssAstNode) => {
          if (item.type === 'declaration') {
            const propNode = (item.value as ScssAstNode[]).find(v => v.type === 'property');
            const valNode = (item.value as ScssAstNode[]).find(v => v.type === 'value');
            if (
              propNode &&
              valNode &&
              (typeof propNode.value === 'string' || typeof propNode.value === 'number')
            ) {
              map[String(propNode.value).replace(/^['"]|['"]$/g, '')] = parseValueNode(valNode);
            }
          }
        });
        return map;
      }
      return values.map((item: ScssNodeValue | ScssAstNode) => parseValueNode(item));
    }
    return node.value.map((item: ScssNodeValue | ScssAstNode) => parseValueNode(item)).join(' ');
  }
  return String(node.value);
}

async function parseScssDefaults(filePath: string): Promise<Partial<Theme>> {
  const fileContent = await fs.readFile(filePath, 'utf8');
  const ast = parse(fileContent);
  const theme: Partial<Theme> = {};
  theme.colors = {};
  theme.fonts = {};

  if (Array.isArray(ast.value)) {
    ast.value.forEach((node: ScssAstNode) => {
      if (node.type === 'declaration') {
        const declarationNode = node as ScssAstNode & { value: ScssAstNode[] };
        const propertyNode = declarationNode.value.find(v => v.type === 'property');
        const valueNode = declarationNode.value.find(v => v.type === 'value');

        if (
          propertyNode &&
          valueNode &&
          typeof propertyNode.value === 'string' &&
          propertyNode.value.startsWith('$')
        ) {
          const variableName = propertyNode.value.substring(1);
          const parsedValue = parseValueNode(valueNode);

          if (variableName.startsWith('color-')) {
            const colorName = variableName.substring('color-'.length);
            if (variableName.endsWith('-light') && typeof parsedValue === 'string') {
              const baseColorName = colorName.replace(/-light$/, '');
              if (
                !theme.colors![baseColorName] ||
                typeof theme.colors![baseColorName] === 'string'
              ) {
                theme.colors![baseColorName] = { light: parsedValue, dark: '' };
              } else {
                (theme.colors![baseColorName] as ColorVariant).light = parsedValue;
              }
            } else if (variableName.endsWith('-dark') && typeof parsedValue === 'string') {
              const baseColorName = colorName.replace(/-dark$/, '');
              if (
                !theme.colors![baseColorName] ||
                typeof theme.colors![baseColorName] === 'string'
              ) {
                theme.colors![baseColorName] = { light: '', dark: parsedValue };
              } else {
                (theme.colors![baseColorName] as ColorVariant).dark = parsedValue;
              }
            } else if (typeof parsedValue === 'string') {
              theme.colors![colorName] = parsedValue;
            }
          } else if (variableName === 'fonts' && isObject(parsedValue)) {
            theme.fonts = parsedValue as FontMap;
          } else if (variableName === 'font-main-path' && typeof parsedValue === 'string') {
            theme.fontMainPath = parsedValue;
          } else if (variableName === 'font-format' && typeof parsedValue === 'string') {
            theme.fontFormat = parsedValue;
          } else if (variableName === 'font-weights' && Array.isArray(parsedValue)) {
            theme.fontWeights = parsedValue.map(String);
          } else if (variableName === 'font-styles' && Array.isArray(parsedValue)) {
            theme.fontStyles = parsedValue.map(String);
          } else if (variableName === 'text-truncate' && typeof parsedValue === 'number') {
            theme.textTruncate = parsedValue;
          } else {
            const camelCaseKey = variableName.replace(/-([a-z])/g, g =>
              g[1].toUpperCase()
            ) as keyof Omit<Theme, keyof ThemeBase>; // Type assertion
            // Ensure that the key is a valid key for additional properties
            if (!(camelCaseKey in theme) || theme[camelCaseKey] === undefined) {
              (theme as Record<string, ThemeValue | ColorMap | FontMap | string[] | undefined>)[
                camelCaseKey
              ] = parsedValue as ThemeValue;
            }
          }
        }
      }
    });
  }
  return theme;
}

async function buildCustomTheme() {
  try {
    const defaultTheme = await parseScssDefaults(defaultsScssPath);
    const userConfig = await loadUserConfig();

    let mergedTheme: Partial<Theme> = defaultTheme;
    if (userConfig) {
      mergedTheme = mergeThemes(defaultTheme, userConfig);
    }

    const finalTheme: Theme = {
      colors: mergedTheme.colors ?? {},
      fontMainPath: mergedTheme.fontMainPath ?? '',
      fontFormat: mergedTheme.fontFormat ?? '',
      fontWeights: mergedTheme.fontWeights ?? [],
      fontStyles: mergedTheme.fontStyles ?? [],
      textTruncate: mergedTheme.textTruncate ?? 0,
      fonts: mergedTheme.fonts ?? {},
      ...(mergedTheme as Omit<Partial<Theme>, keyof ThemeBase>),
    };

    const scssVariablesString = convertThemeToScss(finalTheme);
    await fs.writeFile(generatedVariablesPath, scssVariablesString);

    execSync(`node --loader ts-node/esm ${buildScriptPath}`, { stdio: 'inherit' });
  } catch (errorCaught) {
    console.error('Error during custom theme build:', errorCaught);
    process.exit(1);
  }
}

buildCustomTheme();
