import { Theme } from './types.js'

export function WriteScssVariables(theme: Theme): string {
  const { colors, roles, settings, typography } = theme

  let scss: string = '// Generated by BuildTheme.ts\n // Do not edit this file directly\n\n'

  if (colors) {
    scss += '\n\n// --- Colors ---\n'
    scss += '$colors: (\n'
    for (const [name, modes] of Object.entries(colors)) {
      scss += `"${name}": (\n`
      for (const [mode, value] of Object.entries(modes)) {
        scss += `"${mode}": "${value}",\n`
      }
      scss += `),\n`
    }
    scss += ');\n'
  }

  if (typography) {
    scss += '\n\n// --- Typography ---\n'
    if (typography?.defaultFontFamilies?.length)
      scss += `$defaultFontFamilies: ${typography.defaultFontFamilies.join(', ').replace(/"/g, '')};\n`

    if (typography?.fontMainPath) scss += `$fontMainPath: "${typography.fontMainPath}";\n`
    if (typography?.fontFormat) scss += `$fontFormat: "${typography.fontFormat}";\n`
    if (typography?.fontWeights)
      scss += `$fontWeights: (${typography.fontWeights.map((fW) => `"${fW}"`).join(', ')});\n`
    if (typography?.fontStyles?.length)
      scss += `$fontStyles: (${typography.fontStyles.map((fS) => `"${fS}"`).join(', ')});\n`
    if (typography?.fontSizes?.length) {
      scss += '$fontSizes: (\n'
      for (const [name, value] of Object.entries(typography.fontSizes)) {
        scss += `"${name}": ${value},\n`
      }
      scss += ');\n'
    }
    if (typography?.textTruncate) scss += `$textTruncate: ${typography.textTruncate};\n`
    if (typography?.fonts) {
      scss += '$fonts: (\n'
      for (const [name, font] of Object.entries(typography.fonts)) {
        scss += `"${name}": (\n`
        if (font?.weights) scss += `"weights": (${font.weights.join(', ')}),\n`
        if (font?.styles) scss += `"styles": (${font.styles.join(', ')}),\n`
        if (font?.variants) {
          scss += `"variants": (\n`
          for (const [lang, variant] of Object.entries(font.variants)) {
            scss += `"${lang}": (\n`
            if (variant?.title) scss += `"title": ${variant.title.replace(/"/g, '')},\n`
            if (variant?.unicode) scss += `"unicode": "${variant.unicode}",\n`
            if (variant?.format) scss += `"format": "${variant.format}",\n`
            if (variant?.isLocal) scss += `"isLocal": ${variant.isLocal},\n`
            if (variant?.url) scss += `"url": "${variant.url}",\n`
            scss += '),\n'
          }
          scss += '),\n'
        }
        scss += '),\n'
      }
      scss += ');\n'
    }
  }

  if (settings) {
    scss += '\n\n// --- Settings ---\n'
    if (settings?.axisDivisions) scss += `$axisDivisions: ${settings.axisDivisions};\n`
    if (settings?.opacities) scss += `$opacities: (${settings.opacities.join(', ')});\n`
    if (settings?.blurValues) scss += `$blurValues: (${settings.blurValues.join(', ')});\n`
    if (settings?.insetValues) scss += `$insetValues: (${settings.insetValues.join(', ')});\n`
    if (settings?.bordersValue) scss += `$bordersValue: (${settings.bordersValue.join(', ')});\n`
    if (settings?.radiuses) scss += `$radiuses: (${settings.radiuses.join(', ')});\n`
    if (settings?.breakpoints) {
      scss += `$breakpoints: (\n`
      for (const [key, value] of Object.entries(settings.breakpoints)) {
        scss += `${key}: ${value},\n`
      }
      scss += `);\n`
    }
    if (settings?.wrappers) {
      scss += `$wrappers: (\n`
      for (const [key, wrapper] of Object.entries(settings.wrappers)) {
        scss += `${key}: ${wrapper.width} ${wrapper.padding ?? ''},\n`
      }
      scss += `);\n`
    }
    if (settings?.guttersValues) {
      scss += `$guttersValues: (\n`
      for (const [key, value] of Object.entries(settings.guttersValues)) {
        scss += `${key}: ${value},\n`
      }
      scss += `);\n`
    }
  }

  if (roles) {
    scss += '\n\n// --- Roles ---\n'
    for (const [key, condition] of Object.entries(roles)) {
      scss += `$${key}: ${condition};\n`
    }
  }

  return scss
}
